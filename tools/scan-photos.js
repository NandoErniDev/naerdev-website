#!/usr/bin/env node
/* Scans images/travel/<trip>/<place>/ and writes content/photo-index.js,
   so you do not have to type photo file names into trips.js.
   Run from the project folder:   node tools/scan-photos.js
   - A place uses this index when it has no "photos" list in trips.js.
   - Photos are sorted by file name; cover.* in the trip folder is not a gallery photo.
   - Portrait/landscape is detected for JPEG (including phone rotation) and PNG files.
   - Warns about folders that no place in trips.js points to, and about places without a folder. */
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, "..");
const base = path.join(root, "images", "travel");
const EXT = /\.(jpe?g|png|webp|avif|gif)$/i;

function size(file) {
  try {
    const b = fs.readFileSync(file);
    if (b[0] === 0x89 && b[1] === 0x50) return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
    if (b[0] === 0xff && b[1] === 0xd8) {
      let i = 2, orient = 1;
      while (i < b.length) {
        if (b[i] !== 0xff) { i++; continue; }
        const m = b[i + 1], len = b.readUInt16BE(i + 2);
        if (m === 0xe1 && b.toString("ascii", i + 4, i + 8) === "Exif") {
          const t = i + 10, le = b.toString("ascii", t, t + 2) === "II";
          const r16 = (o) => le ? b.readUInt16LE(o) : b.readUInt16BE(o), r32 = (o) => le ? b.readUInt32LE(o) : b.readUInt32BE(o);
          const ifd = t + r32(t + 4), n = r16(ifd);
          for (let k = 0; k < n; k++) { const e = ifd + 2 + k * 12; if (r16(e) === 0x0112) orient = r16(e + 8); }
        }
        if (m >= 0xc0 && m <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(m)) {
          let h = b.readUInt16BE(i + 5), w = b.readUInt16BE(i + 7);
          if (orient >= 5 && orient <= 8) [w, h] = [h, w];
          return { w, h };
        }
        i += 2 + len;
      }
    }
  } catch (e) {}
  return null;
}

const natural = (a, b) => a.localeCompare(b, undefined, { numeric: true });
const isDir = (p) => fs.statSync(p).isDirectory();
let TRIPS = [];
try { const sb = { window: {} }; vm.runInNewContext(fs.readFileSync(path.join(root, "content", "trips.js"), "utf8"), sb); TRIPS = sb.window.TRIPS || []; } catch (e) { console.warn("Could not read content/trips.js: " + e.message); }
if (!fs.existsSync(base)) { console.error("Folder not found: " + base); process.exit(1); }

const index = {};
let total = 0;
for (const trip of fs.readdirSync(base).filter((d) => isDir(path.join(base, d))).sort(natural)) {
  const tdir = path.join(base, trip);
  index[trip] = {};
  const known = (TRIPS.find((t) => t.id === trip) || {}).stops;
  const folders = fs.readdirSync(tdir).filter((d) => isDir(path.join(tdir, d))).sort(natural);
  let n = 0, placesWithPhotos = 0;
  for (const f of folders) {
    const files = fs.readdirSync(path.join(tdir, f)).filter((x) => EXT.test(x)).sort(natural);
    if (!files.length) continue;
    index[trip][f] = files.map((x) => {
      const s = size(path.join(tdir, f, x));
      return s && s.w / s.h < 0.95 ? { file: x, orientation: "portrait" } : { file: x };
    });
    n += files.length; placesWithPhotos++;
    if (known && !known.some((s) => s.folder === f)) console.warn("  ! " + trip + "/" + f + " has photos but no place in trips.js uses this folder name");
  }
  if (known) known.forEach((s) => { if (!folders.includes(s.folder)) console.warn("  ! " + trip + ": place '" + s.name + "' has no folder '" + s.folder + "'"); });
  const hasCover = fs.readdirSync(tdir).some((x) => /^cover\./i.test(x));
  console.log(trip.padEnd(16), String(n).padStart(4), "photos in", String(placesWithPhotos).padStart(2), "places", hasCover ? "" : "(no cover.* yet)");
  total += n;
}
fs.writeFileSync(path.join(root, "content", "photo-index.js"),
  "/* Generated by:  node tools/scan-photos.js\n   Optional. Used for places whose \"photos\" list in trips.js is empty. */\nwindow.PHOTO_INDEX = " + JSON.stringify(index) + ";\n");
console.log("Wrote content/photo-index.js (" + total + " photos)");
